"""Naming of the config entry of a lock.

The Bluetooth module of a lock advertises a name such as ``WeLockFMHAE``; the cloud needs it to unlock,
but it says nothing to a person. The title of the entry therefore shows the lock number, in
parentheses like the other integrations of this family (``WeLock (22231059)``). A title that the user
chose is never replaced. The identity of the entry stays the Bluetooth address of the module (what
Home Assistant's Bluetooth discovery reports); see docs/ENGINEERING.md.
"""

from __future__ import annotations

import re

TITLE_PREFIX = "WeLock"

# What the integration generated: the module name itself (up to 2.5.0), "WeLock" or "WeLock (<number>)".
_GENERATED_TITLE = re.compile(rf"^{TITLE_PREFIX}( \(.*\))?$")


def lock_title(device_number: str) -> str:
    """Return the title of the entry of the lock with this number."""
    return f"{TITLE_PREFIX} ({device_number})"


def is_generated_title(title: str, ble_name: str) -> bool:
    """Return True if the title was generated by the integration (not chosen by the user)."""
    return title == ble_name or bool(_GENERATED_TITLE.match(title))
